// Writes migrations/0001_auth.sql: the tables Better Auth needs for the options in worker/auth.ts,
// compiled for SQLite against an empty in-memory database. Run again after changing those options
// (then add the difference as a new migration once 0001 has been applied anywhere).
//
//   npm run db:auth-schema
import { writeFileSync } from 'node:fs'
import { DatabaseSync } from 'node:sqlite'

import { getMigrations } from 'better-auth/db/migration'

const { authOptions } = await import('../worker/auth.ts')

const options = { ...authOptions({ BETTER_AUTH_SECRET: 'schema-only-secret-0123456789abcdef' }), database: new DatabaseSync(':memory:') }
const { compileMigrations } = await getMigrations(options)
const sql = await compileMigrations()
writeFileSync('migrations/0001_auth.sql', `-- Generated by scripts/auth-schema.mjs from worker/auth.ts. Do not edit.\n${sql.trim()}\n`)
console.log('wrote migrations/0001_auth.sql')
